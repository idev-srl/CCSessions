func TestReadSession(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "abc-123.jsonl")
	if err := os.WriteFile(path, []byte(`{"type":"user","message":{"content":"hi"}}`+"\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Join(dir, "abc-123", "subagents"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "abc-123", "subagents", "a.jsonl"), make([]byte, 100), 0o644); err != nil {
		t.Fatal(err)
	}
	mt := time.Date(2026, 9, 1, 12, 0, 0, 0, time.UTC)
	if err := os.Chtimes(path, mt, mt); err != nil {
		t.Fatal(err)
	}
	s, err := ReadSession(path)
	if err != nil {
		t.Fatal(err)
	}
	if s.ID != "abc-123" || s.ExtraSize != 100 || s.FileSize == 0 {
		t.Errorf("got %+v", s)
	}
	// No timestamps in the file: both ends fall back to mtime.
	if !s.LastEvent.Equal(mt) || !s.FirstEvent.Equal(mt) {
		t.Errorf("mtime fallback: first=%v last=%v", s.FirstEvent, s.LastEvent)
	}
}
