func TestParseTranscript(t *testing.T) {
	s, err := ParseTranscript(strings.NewReader(sampleTranscript))
	if err != nil {
		t.Fatal(err)
	}
	if s.Cwd != `C:\Users\dev\Proj` {
		t.Errorf("cwd = %q", s.Cwd)
	}
	if s.UserMessages != 2 {
		t.Errorf("user messages = %d, want 2", s.UserMessages)
	}
	if s.AssistantMessages != 2 {
		t.Errorf("assistant messages = %d, want 2 (msg_A counted once, sidechain ignored)", s.AssistantMessages)
	}
	if s.BadLines != 3 {
		t.Errorf("bad lines = %d, want 3", s.BadLines)
	}
	if want := time.Date(2026, 10, 1, 10, 0, 0, 0, time.UTC); !s.FirstEvent.Equal(want) {
		t.Errorf("first = %v", s.FirstEvent)
	}
	if want := time.Date(2026, 10, 1, 11, 30, 1, 0, time.UTC); !s.LastEvent.Equal(want) {
		t.Errorf("last = %v", s.LastEvent)
	}
	if s.FirstPrompt != "Hi, please fix the parser bug" {
		t.Errorf("first prompt = %q", s.FirstPrompt)
	}
	if s.Title != "Fix parser bug" || s.Preview != s.Title {
		t.Errorf("title = %q preview = %q", s.Title, s.Preview)
	}
}

func TestParseTranscriptFallbacks(t *testing.T) {
	// No title: preview is the first prompt. Legacy summary line wins over it.
	s, _ := ParseTranscript(strings.NewReader(`{"type":"user","message":{"content":"just a prompt"}}`))
	if s.Preview != "just a prompt" || s.Cwd != "" {
		t.Errorf("got %+v", s)
	}
	s, _ = ParseTranscript(strings.NewReader("{\"type\":\"user\",\"message\":{\"content\":\"p\"}}\n{\"type\":\"summary\",\"summary\":\"Summary\"}\n"))
	if s.Preview != "Summary" {
		t.Errorf("summary preview = %q", s.Preview)
	}
	// Relative or garbage cwd values are skipped in favour of a later valid one.
	s, _ = ParseTranscript(strings.NewReader("{\"cwd\":\"relative\"}\n{\"cwd\":42}\n{\"cwd\":\"D:/work\"}\n"))
	if s.Cwd != "D:/work" {
		t.Errorf("cwd = %q", s.Cwd)
	}
}

func TestParseTranscriptEmptyAndBinary(t *testing.T) {
	for _, in := range []string{"", "\n\n\n", "\x00\x01\x02\xff\n{{{{", strings.Repeat("x", 1<<20)} {
		s, err := ParseTranscript(strings.NewReader(in))
		if err != nil {
			t.Errorf("unexpected error: %v", err)
		}
		if s.UserMessages != 0 || s.Cwd != "" {
			t.Errorf("unexpected data from garbage: %+v", s)
		}
	}
}

